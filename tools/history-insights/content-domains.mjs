/** 同一关键词出现在多个域时，按 DOMAINS 的先后顺序只保留第一次出现。 */
const OWNERS = new Map();
for (const domain of DOMAINS) {
  const unique = [];
  for (const keyword of domain.keywords) {
    const key = keyword.toLowerCase();
    if (OWNERS.has(key)) continue;
    OWNERS.set(key, domain.id);
    unique.push(key);
  }
  domain.keywords = unique;
}

const MAX_KEYWORD_LENGTH = Math.max(...DOMAINS.flatMap(domain => domain.keywords.map(item => item.length)));

/**
 * 给文本打内容域分数。
 * 命中词越多、词越长（越具体），得分越高；得分相同不做人为补齐，直接判为未归类。
 *
 * @param {string} text 标题 + 标签
 * @returns {{id: string, name: string, color: string, score: number, hits: string[]}|null}
 */
export function classifyContent(text) {
  const source = String(text || '').toLowerCase();
  if (!source) return null;
  const scored = DOMAINS.map(domain => ({ domain, score: 0, hits: [] }));
  for (const item of scored) {
    for (const keyword of item.domain.keywords) {
      if (keyword.length > source.length) continue;
      let index = source.indexOf(keyword);
      while (index !== -1) {
        // 长词权重更高：2 字记 1 分，每多 1 字加 0.4 分，最多 3 分。
        item.score += Math.min(3, 1 + (keyword.length - 2) * 0.4);
        item.hits.push(keyword);
        index = source.indexOf(keyword, index + keyword.length);
      }
    }
  }
  const best = scored.reduce((top, item) => (item.score > top.score ? item : top), scored[0]);
  if (!best || best.score <= 0) return null;
  return { id: best.domain.id, name: best.domain.name, color: best.domain.color, score: Number(best.score.toFixed(2)), hits: [...new Set(best.hits)] };
}

export function domainById(id) {
  return DOMAINS.find(domain => domain.id === id) || null;
}

/**
 * 平台自带的媒体类型也能给出强信号：番剧/电影这类本身就是影视内容，
 * 纪录片属于知识，综艺属于生活娱乐。只在这几个明确的类型上兜底，
 * “视频”“已收藏”等状态字段一律不参与判定。
 */
const MEDIA_TYPE_DOMAINS = {
  '番剧': 'media', '国创': 'media', '动漫': 'media', '动画': 'media',
  '电影': 'media', '电视剧': 'media', '短片': 'media',
  '纪录片': 'knowledge', '综艺': 'life', '真人秀': 'life'
};

export function domainFromMediaType(mediaType) {
  const id = MEDIA_TYPE_DOMAINS[String(mediaType || '').trim()];
  return id ? domainById(id) : null;
}

